export const TEXTOS: Record<Idioma, Record<ClaveTexto, string>> = { es: ES, en: EN, pt: PT };

export type Valores = Record<string, string | number>;

/** El texto en ese idioma, con cada {valor} reemplazado. */
export function traducir(idioma: Idioma, clave: ClaveTexto, valores: Valores = {}): string {
  return TEXTOS[idioma][clave].replace(/\{(\w+)\}/g, (entero, nombre: string) => (nombre in valores ? String(valores[nombre]) : entero));
}
